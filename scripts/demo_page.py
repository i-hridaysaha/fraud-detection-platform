def load(path: Path) -> dict[str, Any]:
    return dict(json.loads(path.read_text(encoding="utf-8")))


def pick(record: dict[str, Any], keys: tuple[str, ...]) -> dict[str, Any]:
    return {k: record[k] for k in keys if k in record}


def provenance(artifact: dict[str, Any], path: str) -> dict[str, Any]:
    return {
        "artifact": path,
        "regenerate_with": artifact.get("regenerate_with"),
        "git_commit": artifact.get("git_commit"),
        "generated_at_utc": artifact.get("generated_at_utc"),
    }


def compact_cycle(cycle: dict[str, Any]) -> dict[str, Any]:
    out: dict[str, Any] = {
        "cycle": cycle["cycle"],
        "as_of_day": cycle["as_of_day"],
        "champion": cycle["champion"],
        "drift": cycle["drift"],
        "decay": [pick(d, DECAY_KEYS) for d in cycle["decay"]],
        "immature": cycle["immature"],
        "decision": cycle["decision"],
    }
    challenger = cycle.get("challenger")
    if challenger is not None:
        record = pick(challenger, CHALLENGER_KEYS)
        if "fit" in challenger:
            record["fit"] = pick(challenger["fit"], FIT_KEYS)
        out["challenger"] = record
    return out


def extract(reports: Path) -> dict[str, Any]:
    """Every number the page shows, read once from the artifacts and shaped for the renderer."""
    lifecycle = load(reports / "lifecycle_demo.json")
    drift = load(reports / "monitoring" / "drift.json")
    decay = load(reports / "monitoring" / "decay.json")
    adversarial = load(reports / "adversarial_validation.json")
    variance = load(reports / "metric_variance.json")
    operating = load(reports / "operating_points.json")
    latency = load(reports / "latency.json")
    parity = load(reports / "parity.json")
    split = load(reports / "split_summary.json")

    shipped = variance["by_row"]["per_model"]["shipped"]
    xgb_p50 = latency["summary"]["pinned_p50_by_family"]["xgboost"]
    xgb_p99 = latency["summary"]["pinned_p99_by_family"]["xgboost"]
    memory = parity["backends"]["memory"]
    calibration = drift["calibration"]
    in_control_drift = drift["in_control"]
    in_control_decay = decay["in_control"]
    fits = adversarial["fits"]

    def fit_summary(name: str) -> dict[str, Any]:
        fit = fits[name]
        return {
            "n_columns": fit["n_columns"],
            "auc_out_of_fold": fit["auc"]["out_of_fold"],
            "entity_and_clock_share_of_top_10_gain": fit["entity_and_clock_share_of_top_10_gain"],
            "top": [
                pick(row, ("rank", "column", "group", "gain_share")) for row in fit["top"][:10]
            ],
        }

    return {
        "run": {
            "generated_at_utc": lifecycle["generated_at_utc"],
            "git_commit": lifecycle["git_commit"],
            "seed": lifecycle["seed"],
            "seconds": lifecycle["seconds"],
            "regenerate_with": lifecycle["regenerate_with"],
            "environment": lifecycle["environment"],
        },
        "headline": {
            "pr_auc": {
                "point": shipped["point"],
                "low": shipped["low"],
                "high": shipped["high"],
                "half_width": shipped["half_width"],
                "n_boot": variance["by_row"]["n_boot"],
                "resample": variance["by_row"]["resample"],
            },
            "roc_auc_test": operating["primary_metric"]["test"]["roc_auc"],
            "n_rows": split["totals"]["n_rows"],
            "n_train_rows": split["splits"]["train"]["n_rows"],
            "n_test_rows": split["splits"]["test"]["n_rows"],
            "fraud_rate": split["totals"]["fraud_rate"],
            "n_columns": latency["models"]["n_columns"],
            "latency": {
                "p50_ms_median": xgb_p50["median"],
                "p99_ms_median": xgb_p99["median"],
                "n_repeats": latency["summary"]["n_repeats"],
                "n_rows": latency["method"]["rows"]["n"],
                "inference_threads": latency["pinning"]["inference_threads"],
            },
            "parity": {
                "n_rows": parity["stream"]["n_rows"],
                "n_days": parity["stream"]["n_days"],
                "n_features": memory["n_features"],
                "max_abs_difference": memory["max_abs_difference_over_all_features"],
                "bit_identical": memory["bit_identical"],
            },
        },
        "inputs": lifecycle["inputs"],
        "stream": lifecycle["stream"],
        "champion": lifecycle["champion"],
        "noise_band": {
            "by_card": variance["by_card"]["widest_paired_half_width"],
            "by_row": variance["by_row"]["widest_paired_half_width"],
            "n_boot": variance["n_boot"],
        },
        "drift_job": {
            "n_columns": calibration["n_columns"],
            "n_alertable_columns": calibration["n_alertable_columns"],
            "n_batches": calibration["n_batches"],
            "batch_days": calibration["batch_days"],
            "feature_count_edge": calibration["feature_count_edge"],
            "score_alert_edge": calibration["score_alert_edge"],
            "worst_batch_score_psi": calibration["worst_batch_score_psi"],
            "textbook_alert_band_per_batch": in_control_drift["textbook_alert_band_per_batch"],
            "calibrated_alerts_per_batch": in_control_drift["calibrated_alerts_per_batch"],
            "score_psi_per_batch": in_control_drift["score_psi_per_batch"],
            "longest_run_of_drift_alerts": in_control_drift["longest_run_of_drift_alerts"],
            "leave_one_out_rate_any_alert": in_control_drift["leave_one_out"]["rate_any_alert"],
            "stage_2_psi_test_above_0_10": drift["against_stage_2"]["stage_2_summary"][
                "n_psi_test_above_0_10"
            ],
        },
        "decay_job": {
            "maturity_days": decay["maturity_days"],
            "reference": {
                "window": decay["reference"]["window"],
                "pr_auc": decay["reference"]["pr_auc"],
                "n_rows": decay["reference"]["n_rows"],
                "n_fraud": decay["reference"]["n_fraud"],
                "threshold": decay["reference"]["threshold"],
            },
            "n_batches": in_control_decay["n_batches"],
            "pr_auc_per_batch": in_control_decay["pr_auc_per_batch"],
            "drop_per_batch": in_control_decay["drop_per_batch"],
            "largest_drop": in_control_decay["largest_drop"],
            "n_decay": in_control_decay["n_decay"],
            "decay_tolerance": in_control_decay["decay_tolerance"],
            "headroom": in_control_decay["headroom"],
        },
        "adversarial": {
            "n_train_rows": adversarial["n_train_rows"],
            "n_test_rows": adversarial["n_test_rows"],
            "fits": {name: fit_summary(name) for name in fits},
            "spearman_gain_vs_stage_2_psi": adversarial["against_stage_2"][
                "spearman_gain_vs_stage_2_psi"
            ]["rho"],
        },
        "cycles": [compact_cycle(c) for c in lifecycle["cycles"]],
        "promotion": {
            "cycle": lifecycle["promotion"]["cycle"],
            "version": lifecycle["promotion"]["version"],
            "previous_version": lifecycle["promotion"]["previous_version"],
            "new_reference_pr_auc": lifecycle["promotion"]["new_reference_pr_auc"],
            "new_drift_reference": lifecycle["promotion"]["new_drift_reference"],
        },
        "rollback": lifecycle["rollback"],
        "sources": [
            provenance(lifecycle, "reports/lifecycle_demo.json"),
            provenance(drift, "reports/monitoring/drift.json"),
            provenance(decay, "reports/monitoring/decay.json"),
            provenance(adversarial, "reports/adversarial_validation.json"),
            provenance(variance, "reports/metric_variance.json"),
            provenance(operating, "reports/operating_points.json"),
            provenance(latency, "reports/latency.json"),
            provenance(parity, "reports/parity.json"),
            provenance(split, "reports/split_summary.json"),
        ],
    }


def render(data: dict[str, Any]) -> str:
    payload = json.dumps(data, sort_keys=True, separators=(",", ":")).replace("</", "<\\/")
    return TEMPLATE.replace("__DATA__", payload)


