"""Build the lifecycle demo page from the committed stage 9 artifacts. Writes docs/demo/index.html.

Usage:
    make demo-page
    .venv/bin/python scripts/demo_page.py

The page is one self-contained HTML file for a static host: every number it shows is read from
an artifact under reports/ at build time and inlined as JSON, and the page's own script renders
it. It reads no data and fits no model, so a copy of the file is the whole deployment. The
committed page is regenerated by this script alone and a test compares the two byte for byte,
so the page can never quote a number the artifacts do not hold.

What the page replays, all from reports/lifecycle_demo.json: the fourteen weekly cycles of the
seed-pinned run, the drift job at each batch close, the decay job as each batch's labels mature,
the retrain decision, the four challengers at the gate, the two promotions and the rollback
drill. The headline tiles read reports/metric_variance.json, reports/operating_points.json,
reports/latency.json, reports/parity.json and reports/split_summary.json; the inputs card reads
reports/monitoring/drift.json and reports/monitoring/decay.json; the drift character card reads
reports/adversarial_validation.json.
"""

